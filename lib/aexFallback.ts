export function getAexFallback(year = new Date().getUTCFullYear()): AexSnapshot | null {
  if (year !== 2026) return null;

  const points = fallback2026.map(([date, close]) => ({
    timestamp: Math.floor(Date.parse(`${date}T12:00:00Z`) / 1000),
    close,
  }));

  return { latest: points.at(-1)!.close, points };
}
